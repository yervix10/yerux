use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

#[derive(Debug)]
struct Dependency {
    name: String,
    value: String,
    git: bool,
    tag: Option<String>,
    /// version requirement (`^1.2`, `~1.2`, `>=1.0`, `=1.2.3`, `1.2`, `*`) the package must satisfy
    version: Option<String>,
}

fn quoted(s: &str) -> Option<String> {
    let s = s.trim();
    let s = s.strip_prefix('"')?.strip_suffix('"')?;
    Some(s.to_string())
}

fn manifest(root: &Path) -> Result<(String, String, Vec<Dependency>), String> {
    let text = fs::read_to_string(root.join("yerux.toml"))
        .map_err(|e| format!("cannot read yerux.toml: {e}"))?;
    let mut section = "";
    let (mut name, mut version) = (None, None);
    let mut deps: Vec<Dependency> = Vec::new();
    for raw in text.lines() {
        let line = raw.split('#').next().unwrap_or("").trim();
        if line.starts_with('[') && line.ends_with(']') {
            section = &line[1..line.len() - 1];
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let (key, value) = (key.trim(), value.trim());
        if section == "package" {
            if key == "name" {
                name = quoted(value);
            }
            if key == "version" {
                version = quoted(value);
            }
        } else if section == "dependencies" {
            let mut dep = Dependency {
                name: key.to_string(),
                value: String::new(),
                git: false,
                tag: None,
                version: None,
            };
            if value.starts_with('"') {
                dep.value = quoted(value).ok_or("invalid dependency path")?;
            } else {
                for field in value
                    .trim_start_matches('{')
                    .trim_end_matches('}')
                    .split(',')
                {
                    if let Some((k, v)) = field.split_once('=') {
                        match k.trim() {
                            "path" => dep.value = quoted(v).ok_or("invalid dependency path")?,
                            "git" => {
                                dep.value = quoted(v).ok_or("invalid git URL")?;
                                dep.git = true;
                            }
                            "tag" => dep.tag = quoted(v),
                            "version" => {
                                let r = quoted(v).ok_or("invalid version requirement")?;
                                Req::parse(&r)?;
                                dep.version = Some(r);
                            }
                            _ => return Err(format!("unknown dependency field {}", k.trim())),
                        }
                    }
                }
            }
            if dep.value.is_empty() {
                return Err(format!("dependency {} needs path or git", dep.name));
            }
            deps.push(dep);
        }
    }
    Ok((
        name.ok_or("missing [package].name")?,
        version.ok_or("missing [package].version")?,
        deps,
    ))
}

fn resolve(root: &Path, deps: &[Dependency]) -> Result<(), String> {
    let mut lock = String::from("# Generated by yerux; do not edit.\n");
    for dep in deps {
        let resolved = if dep.git {
            let dir = root.join(".yerux/git").join(&dep.name);
            // a checkout is reused only for the same url and tag
            let marker = root.join(".yerux/git").join(format!("{}.rev", dep.name));
            let wanted = format!("{}\n{}\n", dep.value, dep.tag.as_deref().unwrap_or(""));
            if dir.exists() && fs::read_to_string(&marker).ok().as_deref() != Some(wanted.as_str()) {
                let _ = fs::remove_dir_all(&dir);
            }
            if !dir.exists() {
                fs::create_dir_all(dir.parent().unwrap()).map_err(|e| e.to_string())?;
                let mut cmd = Command::new("git");
                cmd.args(["clone", "--quiet"]);
                if let Some(tag) = &dep.tag {
                    cmd.args(["--branch", tag, "--depth", "1"]);
                }
                let status = cmd
                    .arg(&dep.value)
                    .arg(&dir)
                    .status()
                    .map_err(|e| format!("git clone failed: {e}"))?;
                if !status.success() {
                    return Err(format!("git clone failed for {}", dep.name));
                }
                fs::write(&marker, &wanted).map_err(|e| e.to_string())?;
            }
            dir
        } else {
            let path = root.join(&dep.value);
            if !path.join("yerux.toml").is_file() {
                return Err(format!(
                    "dependency {} has no yerux.toml at {}",
                    dep.name,
                    path.display()
                ));
            }
            path
        };
        let (_, found, _) = manifest(&resolved)
            .map_err(|e| format!("dependency {}: {e}", dep.name))?;
        if let Some(req) = &dep.version {
            let ok = Ver::parse(&found).is_some_and(|v| Req::parse(req).is_ok_and(|r| r.matches(&v)));
            if !ok {
                return Err(format!(
                    "dependency {} is version {} but yerux.toml requires {}",
                    dep.name, found, req
                ));
            }
        }
        lock.push_str(&format!(
            "\n[[package]]\nname = \"{}\"\nversion = \"{}\"\nsource = \"{}\"\n",
            dep.name,
            found,
            resolved.display()
        ));
        if let Some(tag) = &dep.tag {
            lock.push_str(&format!("tag = \"{}\"\n", tag));
        }
    }
    fs::write(root.join("yerux.lock"), lock).map_err(|e| format!("cannot write yerux.lock: {e}"))
}

pub fn new_project(name: &str) -> Result<(), String> {
    let root = Path::new(name);
    let package_name = root.file_name().and_then(|s| s.to_str()).unwrap_or(name);
    fs::create_dir_all(root.join("src")).map_err(|e| e.to_string())?;
    fs::create_dir_all(root.join("tests")).map_err(|e| e.to_string())?;
    fs::write(
        root.join("yerux.toml"),
        format!(
            "[package]\nname = \"{}\"\nversion = \"0.1.0\"\n\n[dependencies]\n",
            package_name
        ),
    )
    .map_err(|e| e.to_string())?;
    fs::write(
        root.join("src/main.yx"),
        "fn main() {\n    print(\"Hello from Yerux!\")\n}\n",
    )
    .map_err(|e| e.to_string())?;
    Ok(())
}

pub fn run(command: &str) -> Result<i32, String> {
    let root = std::env::current_dir().map_err(|e| e.to_string())?;
    let (name, _, deps) = manifest(&root)?;
    resolve(&root, &deps)?;
    let entry = root.join("src/main.yx");
    if command == "test" {
        let dir = root.join("tests");
        let mut files: Vec<PathBuf> = fs::read_dir(&dir)
            .map_err(|e| format!("cannot read tests/: {e}"))?
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "yx"))
            .collect();
        files.sort();
        if files.is_empty() {
            println!("no tests found");
            return Ok(0);
        }
        let args = files
            .iter()
            .map(|p| p.to_string_lossy().into_owned())
            .collect::<Vec<_>>();
        return Ok(crate::run_tests(&args));
    }
    if !entry.is_file() {
        return Err("missing src/main.yx".into());
    }
    let bin = root.join("target").join(&name);
    fs::create_dir_all(bin.parent().unwrap()).map_err(|e| e.to_string())?;
    let mut args = vec![
        command.to_string(),
        entry.to_string_lossy().into_owned(),
        "-o".into(),
        bin.to_string_lossy().into_owned(),
    ];
    if command == "build" {
        let st = Command::new(std::env::current_exe().map_err(|e| e.to_string())?)
            .args(&args)
            .status()
            .map_err(|e| e.to_string())?;
        return Ok(st.code().unwrap_or(1));
    }
    args.truncate(2);
    let st = Command::new(std::env::current_exe().map_err(|e| e.to_string())?)
        .args(args)
        .status()
        .map_err(|e| e.to_string())?;
    Ok(st.code().unwrap_or(1))
}

