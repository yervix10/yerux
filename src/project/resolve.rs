use super::manifest::{self, Dependency, Location, Manifest};
use super::store::{canonical, checkout, git_url, is_revision, relative, Refs};
use semver::{Version, VersionReq};
use serde::{Deserialize, Serialize};
use std::{
    collections::{BTreeMap, BTreeSet, HashMap},
    fs, io,
    path::{Path, PathBuf},
};

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub(super) enum Kind {
    Path,
    Git,
    GitLocal,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub(super) struct Pin {
    pub kind: Kind,
    pub source: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tag: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub rev: Option<String>,
}

#[derive(Debug, PartialEq, Eq, Serialize, Deserialize)]
struct LockedPackage {
    name: String,
    version: Version,
    #[serde(flatten)]
    pin: Pin,
    dependencies: Vec<String>,
}

#[derive(Debug, PartialEq, Eq, Serialize, Deserialize)]
struct Lock {
    format: u32,
    name: String,
    version: Version,
    dependencies: Vec<String>,
    #[serde(default, rename = "package", skip_serializing_if = "Vec::is_empty")]
    packages: Vec<LockedPackage>,
}

impl Lock {
    fn read(root: &Path) -> Result<Option<Self>, String> {
        let text = match fs::read_to_string(root.join("yerux.lock")) {
            Ok(text) => text,
            Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(None),
            Err(e) => return Err(format!("cannot read yerux.lock: {e}")),
        };
        let doc: toml_edit::DocumentMut = text
            .parse::<toml_edit::DocumentMut>()
            .map_err(|e| format!("invalid yerux.lock: {e}"))?;
        // Older locks recorded checkout paths, with no revision to reuse.
        if doc.get("format").is_none() {
            return Ok(None);
        }
        let lock: Self =
            toml_edit::de::from_str(&text).map_err(|e| format!("invalid yerux.lock: {e}"))?;
        if lock.format != 1 {
            return Err(format!("unsupported yerux.lock format {}", lock.format));
        }
        let mut names = BTreeSet::new();
        for p in &lock.packages {
            let valid = match p.pin.kind {
                Kind::Path => p.pin.rev.is_none() && p.pin.tag.is_none(),
                _ => p.pin.rev.as_deref().is_some_and(is_revision),
            };
            if !manifest::valid_dependency(&p.name) || !names.insert(&p.name) || !valid {
                return Err(format!("invalid yerux.lock entry for {}", p.name));
            }
        }
        Ok(Some(lock))
    }

    fn text(&self) -> Result<String, String> {
        let body = toml_edit::ser::to_string_pretty(self).map_err(|e| e.to_string())?;
        Ok(format!(
            "# Generated by yerux. Commit this file with yerux.toml.\n{body}"
        ))
    }
}

#[derive(Clone)]
pub(super) struct Selected {
    pub manifest: Manifest,
    pub root: PathBuf,
    pin: Pin,
    checkout: Option<PathBuf>,
}

#[derive(Clone)]
pub struct Graph {
    pub manifest: Manifest,
    packages: BTreeMap<String, Selected>,
}

impl Graph {
    pub fn tag(&self, name: &str) -> Option<&str> {
        self.packages.get(name)?.pin.tag.as_deref()
    }

    pub fn version(&self, name: &str) -> Option<&Version> {
        Some(&self.packages.get(name)?.manifest.version)
    }

    fn lock(&self) -> Lock {
        Lock {
            format: 1,
            name: self.manifest.name.clone(),
            version: self.manifest.version.clone(),
            dependencies: self.manifest.dependencies.keys().cloned().collect(),
            packages: self
                .packages
                .values()
                .map(|p| LockedPackage {
                    name: p.manifest.name.clone(),
                    version: p.manifest.version.clone(),
                    pin: p.pin.clone(),
                    dependencies: p.manifest.dependencies.keys().cloned().collect(),
                })
                .collect(),
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Mode {
    Reuse,
    Locked,
    Update,
}

pub(super) fn resolve(
    root: &Path,
    manifest: Manifest,
    mode: Mode,
) -> Result<(Graph, Option<String>), String> {
    let old = Lock::read(root)?;
    if mode == Mode::Locked && old.is_none() {
        return Err("missing or legacy yerux.lock; run yerux lock first".into());
    }
    let mut resolver = Resolver {
        root,
        pins: if mode == Mode::Update {
            None
        } else {
            old.as_ref()
        },
        mode,
        refs: HashMap::new(),
    };
    let mut requests = Vec::new();
    pending(&mut requests, root, &manifest, None, &[]);
    let packages = resolver.solve(BTreeMap::new(), requests)?;
    let graph = Graph {
        manifest,
        packages,
    };
    let lock = graph.lock();
    if old.as_ref() == Some(&lock) {
        return Ok((graph, None));
    }
    if mode == Mode::Locked {
        return Err("yerux.lock is out of date; run yerux lock".into());
    }
    Ok((graph, Some(lock.text()?)))
}

#[derive(Clone)]
struct Request {
    owner: PathBuf,
    name: String,
    dep: Dependency,
    checkout: Option<PathBuf>,
    chain: Vec<String>,
}

fn pending(
    queue: &mut Vec<Request>,
    root: &Path,
    manifest: &Manifest,
    checkout: Option<&Path>,
    chain: &[String],
) {
    let mut chain = chain.to_vec();
    chain.push(manifest.name.clone());
    queue.extend(
        manifest
            .dependencies
            .iter()
            .rev()
            .map(|(name, dep)| Request {
                owner: root.to_owned(),
                name: name.clone(),
                dep: dep.clone(),
                checkout: checkout.map(Path::to_owned),
                chain: chain.clone(),
            }),
    );
}

struct Resolver<'a> {
    root: &'a Path,
    pins: Option<&'a Lock>,
    mode: Mode,
    refs: HashMap<String, Refs>,
}

impl Resolver<'_> {
    fn solve(
        &mut self,
        mut selected: BTreeMap<String, Selected>,
        mut queue: Vec<Request>,
    ) -> Result<BTreeMap<String, Selected>, String> {
        while let Some(req) = queue.pop() {
            if req.chain.contains(&req.name) {
                return Err(format!(
                    "package dependency cycle: {} -> {}",
                    req.chain.join(" -> "),
                    req.name
                ));
            }
            let source = self.source(&req)?;
            if let Some(found) = selected.get(&req.name) {
                if !req.accepts(&source, found) {
                    return Err(format!(
                        "dependency conflict in {}: {} {} from {} does not satisfy {}",
                        req.chain.join(" -> "),
                        req.name,
                        found.manifest.version,
                        found.pin.source,
                        req.description(&source)
                    ));
                }
                continue;
            }
            if source.kind == Kind::Path {
                let entry = self.load(&req, source)?;
                pending(
                    &mut queue,
                    &entry.root,
                    &entry.manifest,
                    entry.checkout.as_deref(),
                    &req.chain,
                );
                selected.insert(req.name, entry);
                continue;
            }

            let old = self
                .pins
                .and_then(|lock| lock.packages.iter().find(|p| p.name == req.name))
                .filter(|p| req.accepts_pin(&source, &p.pin) && req.accepts_version(&p.version))
                .map(|p| p.pin.clone());
            let mut error = None;
            if let Some(pin) = &old {
                match self.branch(&req, pin.clone(), &selected, &queue) {
                    Ok(solution) => return Ok(solution),
                    Err(e) => error = Some(e),
                }
            }
            if self.mode == Mode::Locked {
                return Err(error.unwrap_or_else(|| {
                    format!("yerux.lock needs a pin for {}; run yerux lock", req.name)
                }));
            }
            let candidates = self
                .git_candidates(&req, &source)
                .map_err(|e| error.take().unwrap_or(e))?;
            for pin in candidates {
                if old.as_ref() == Some(&pin) {
                    continue;
                }
                match self.branch(&req, pin, &selected, &queue) {
                    Ok(solution) => return Ok(solution),
                    Err(e) if error.is_none() => error = Some(e),
                    Err(_) => {}
                }
            }
            return Err(error.unwrap_or_else(|| {
                format!(
                    "no git revision for {} satisfies {}",
                    req.name,
                    req.description(&source)
                )
            }));
        }
        Ok(selected)
    }

    fn branch(
        &mut self,
        request: &Request,
        pin: Pin,
        selected: &BTreeMap<String, Selected>,
        queue: &[Request],
    ) -> Result<BTreeMap<String, Selected>, String> {
        let chosen = self.load(request, pin)?;
        let mut selected = selected.clone();
        let mut queue = queue.to_vec();
        pending(
            &mut queue,
            &chosen.root,
            &chosen.manifest,
            chosen.checkout.as_deref(),
            &request.chain,
        );
        selected.insert(request.name.clone(), chosen);
        self.solve(selected, queue)
    }

    fn source(&self, req: &Request) -> Result<Pin, String> {
        let (kind, source) = match &req.dep.source {
            Location::Path(path) => {
                let path = canonical(&req.owner.join(path))?;
                if req
                    .checkout
                    .as_ref()
                    .is_some_and(|checkout| !path.starts_with(checkout))
                {
                    return Err(format!(
                        "git dependency {} uses a path outside its checkout",
                        req.name
                    ));
                }
                (Kind::Path, relative(self.root, &path)?)
            }
            Location::Git(path)
                if Path::new(path).is_absolute()
                    || path.starts_with('.')
                    || !path.contains(':') =>
            {
                let path = req.owner.join(path);
                // The repository can be offline or moved while its pinned checkout remains usable.
                let path = fs::canonicalize(&path).unwrap_or_else(|_| path.components().collect());
                (Kind::GitLocal, relative(self.root, &path)?)
            }
            Location::Git(url) => (Kind::Git, url.clone()),
        };
        Ok(Pin {
            kind,
            source,
            tag: None,
            rev: None,
        })
    }

    fn load(&self, req: &Request, pin: Pin) -> Result<Selected, String> {
        let (root, checkout) = if pin.kind == Kind::Path {
            (self.root.join(&pin.source), req.checkout.clone())
        } else {
            let root = checkout(self.root, &pin)?;
            (root.clone(), Some(root))
        };
        let manifest =
            Manifest::read(&root).map_err(|e| format!("dependency {}: {e}", req.name))?;
        if manifest.name != req.name {
            return Err(format!(
                "{} is the package {:?}, not {:?}",
                root.display(),
                manifest.name,
                req.name
            ));
        }
        if !req.accepts_version(&manifest.version) {
            return Err(format!(
                "{} is version {}, which does not satisfy {}",
                req.name,
                manifest.version,
                req.description(&pin)
            ));
        }
        if let Some(tag_version) = req.tag_version(&pin) {
            if tag_version != manifest.version {
                return Err(format!(
                    "git tag {} for {} declares version {}",
                    pin.tag.as_deref().unwrap(),
                    req.name,
                    manifest.version
                ));
            }
        }
        Ok(Selected {
            manifest,
            root,
            pin,
            checkout,
        })
    }

    fn git_candidates(&mut self, req: &Request, source: &Pin) -> Result<Vec<Pin>, String> {
        let url = git_url(self.root, source);
        if !self.refs.contains_key(&url) {
            self.refs.insert(url.clone(), Refs::read(&url)?);
        }
        let refs = &self.refs[&url];
        let candidates: Vec<_> = if let Some(tag) = &req.dep.tag {
            refs.tags
                .get(tag)
                .map(|rev| (Some(tag.to_owned()), rev.clone()))
                .into_iter()
                .collect()
        } else {
            let mut tags: Vec<_> = refs
                .tags
                .iter()
                .filter_map(|(tag, rev)| {
                    let version = manifest::version(tag).ok();
                    if let Some(requirement) = &req.dep.requirement {
                        if !version.as_ref().is_some_and(|v| requirement.matches(v)) {
                            return None;
                        }
                    }
                    Some((version, tag, rev))
                })
                .collect();
            tags.sort_by(|(a, at, _), (b, bt, _)| {
                match (a, b) {
                    (Some(a), Some(b)) => b.cmp_precedence(a),
                    _ => b.is_some().cmp(&a.is_some()),
                }
                .then_with(|| at.cmp(bt))
            });
            // An unqualified git edge prefers HEAD but can share a tag required
            // by another edge discovered later in the graph.
            let head = refs.head.as_ref().filter(|_| req.dep.requirement.is_none());
            head.map(|rev| (None, rev.clone()))
                .into_iter()
                .chain(
                    tags.into_iter()
                        .map(|(_, tag, rev)| (Some(tag.clone()), rev.clone())),
                )
                .collect()
        };
        Ok(candidates
            .into_iter()
            .map(|(tag, rev)| Pin {
                kind: source.kind.clone(),
                source: source.source.clone(),
                tag,
                rev: Some(rev),
            })
            .collect())
    }
}

impl Request {
    fn accepts_version(&self, version: &Version) -> bool {
        self.dep
            .requirement
            .as_ref()
            .is_none_or(|req| req.matches(version))
    }

    fn tag_version(&self, pin: &Pin) -> Option<Version> {
        if self.dep.tag.is_none() && self.dep.requirement.is_some() {
            pin.tag
                .as_deref()
                .and_then(|tag| manifest::version(tag).ok())
        } else {
            None
        }
    }

    fn accepts_pin(&self, source: &Pin, pin: &Pin) -> bool {
        pin.kind == source.kind
            && pin.source == source.source
            && self
                .dep
                .tag
                .as_ref()
                .is_none_or(|tag| pin.tag.as_ref() == Some(tag))
            && (source.kind == Kind::Path
                || self.dep.tag.is_some()
                || self.dep.requirement.is_none()
                || self
                    .tag_version(pin)
                    .is_some_and(|version| self.accepts_version(&version)))
    }

    fn accepts(&self, source: &Pin, selected: &Selected) -> bool {
        self.accepts_pin(source, &selected.pin)
            && self.accepts_version(&selected.manifest.version)
            && self
                .tag_version(&selected.pin)
                .is_none_or(|v| v == selected.manifest.version)
    }

    fn description(&self, source: &Pin) -> String {
        let mut text = source.source.clone();
        if let Some(tag) = &self.dep.tag {
            text.push_str(&format!(" (tag {tag})"));
        }
        if let Some(req) = &self.dep.requirement {
            text.push_str(&format!(" (version {req})"));
        }
        text
    }
}

pub(super) fn latest_tag(root: &Path, url: &str) -> Result<Option<String>, String> {
    let request = Request {
        owner: root.to_owned(),
        name: String::new(),
        checkout: None,
        chain: vec![],
        dep: Dependency {
            source: Location::Git(url.into()),
            tag: None,
            requirement: Some(VersionReq::STAR),
        },
    };
    let mut resolver = Resolver {
        root,
        pins: None,
        mode: Mode::Update,
        refs: HashMap::new(),
    };
    let source = resolver.source(&request)?;
    Ok(resolver
        .git_candidates(&request, &source)?
        .into_iter()
        .find_map(|pin| pin.tag))
}
